#[allow(clippy::cast_possible_truncation)]
fn strict_i16(value: &RenewalShopQueryValue, column: usize) -> Result<i16, RenewalShopRowError> {
    let bytes = raw_cell_bytes(value, column)?;
    let (negative, magnitude) = strict_decimal_parts(bytes, column, "i16", true)?;
    let max = if negative {
        1_u128 << 15
    } else {
        (1_u128 << 15) - 1
    };
    if magnitude > max {
        return Err(RenewalShopRowError::NumberOverflow {
            column,
            value: bounded_value(bytes),
            target: "i16",
        });
    }
    if negative {
        if magnitude == (1_u128 << 15) {
            Ok(i16::MIN)
        } else {
            Ok(-(magnitude as i16))
        }
    } else {
        Ok(magnitude as i16)
    }
}

#[allow(clippy::cast_possible_truncation)]
fn strict_u64(value: &RenewalShopQueryValue, column: usize) -> Result<u64, RenewalShopRowError> {
    let bytes = raw_cell_bytes(value, column)?;
    let (negative, magnitude) = strict_decimal_parts(bytes, column, "u64", false)?;
    if negative || magnitude > u128::from(u64::MAX) {
        return Err(RenewalShopRowError::NumberOverflow {
            column,
            value: bounded_value(bytes),
            target: "u64",
        });
    }
    Ok(magnitude as u64)
}

fn is_c_whitespace(byte: u8) -> bool {
    matches!(byte, b' ' | b'\t' | b'\n' | 0x0b | 0x0c | b'\r')
}

#[derive(Debug, Clone, Copy)]
struct LegacyScan {
    negative: bool,
    has_digit: bool,
    magnitude: u128,
    saturated: bool,
}

fn scan_legacy_number(bytes: &[u8]) -> LegacyScan {
    let mut offset = 0;
    while offset < bytes.len() && is_c_whitespace(bytes[offset]) {
        offset += 1;
    }
    let mut negative = false;
    if offset < bytes.len() && (bytes[offset] == b'+' || bytes[offset] == b'-') {
        negative = bytes[offset] == b'-';
        offset += 1;
    }
    let mut magnitude = 0_u128;
    let mut saturated = false;
    let mut has_digit = false;
    while offset < bytes.len() {
        let byte = bytes[offset];
        if !byte.is_ascii_digit() {
            break;
        }
        has_digit = true;
        let digit = u128::from(byte - b'0');
        if !saturated {
            match magnitude
                .checked_mul(10)
                .and_then(|value| value.checked_add(digit))
            {
                Some(value) => magnitude = value,
                None => saturated = true,
            }
        }
        offset += 1;
    }
    LegacyScan {
        negative,
        has_digit,
        magnitude,
        saturated,
    }
}

#[allow(clippy::cast_possible_truncation)]
fn legacy_i32_from_bytes(bytes: &[u8]) -> i32 {
    let scan = scan_legacy_number(bytes);
    if !scan.has_digit {
        return 0;
    }
    let limit = 1_u128 << 31;
    if scan.saturated || scan.magnitude > limit {
        return if scan.negative { i32::MIN } else { i32::MAX };
    }
    if scan.negative {
        if scan.magnitude == limit {
            i32::MIN
        } else {
            -(scan.magnitude as i32)
        }
    } else {
        scan.magnitude as i32
    }
}

#[allow(clippy::cast_possible_truncation)]
fn legacy_u32_from_bytes(bytes: &[u8]) -> u32 {
    let scan = scan_legacy_number(bytes);
    if !scan.has_digit {
        return 0;
    }
    if scan.saturated || scan.magnitude > u128::from(u32::MAX) {
        return u32::MAX;
    }
    let magnitude = scan.magnitude as u32;
    if scan.negative {
        0_u32.wrapping_sub(magnitude)
    } else {
        magnitude
    }
}

#[allow(clippy::cast_possible_truncation)]
fn legacy_u64_from_bytes(bytes: &[u8]) -> u64 {
    let scan = scan_legacy_number(bytes);
    if !scan.has_digit {
        return 0;
    }
    if scan.saturated || scan.magnitude > u128::from(u64::MAX) {
        return u64::MAX;
    }
    let magnitude = scan.magnitude as u64;
    if scan.negative {
        0_u64.wrapping_sub(magnitude)
    } else {
        magnitude
    }
}

fn legacy_optional<T>(
    value: &RenewalShopQueryValue,
    column: usize,
    parse: fn(&[u8]) -> T,
) -> Result<Option<T>, RenewalShopRowError> {
    match value {
        RenewalShopQueryValue::Null => Ok(None),
        RenewalShopQueryValue::Error(message) => Err(RenewalShopRowError::Source {
            column,
            message: message.clone(),
        }),
        RenewalShopQueryValue::Text(text) => {
            let bytes = text.as_bytes();
            if bytes.is_empty() || bytes.first() == Some(&0) {
                Ok(None)
            } else {
                Ok(Some(parse(bytes)))
            }
        }
        RenewalShopQueryValue::Bytes(bytes) => {
            if bytes.is_empty() || bytes.first() == Some(&0) {
                Ok(None)
            } else {
                Ok(Some(parse(bytes)))
            }
        }
    }
}

