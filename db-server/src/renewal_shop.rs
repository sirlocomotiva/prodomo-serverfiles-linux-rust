/// One raw value returned by a renewal-shop query adapter.
///
/// `Text` and `Bytes` are both non-NULL facts.  `Bytes` is lossless for
/// non-UTF-8 driver data and embedded NULs.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum RenewalShopQueryValue {
    /// A non-NULL textual SQL value.
    Text(String),
    /// A non-NULL raw SQL value.
    Bytes(Vec<u8>),
    /// A SQL `NULL` value.
    Null,
    /// An extraction or source error.
    Error(String),
}

impl RenewalShopQueryValue {
    /// Construct a non-NULL textual value.
    #[must_use]
    pub fn text(value: impl Into<String>) -> Self {
        Self::Text(value.into())
    }

    /// Copy a non-NULL raw value.
    #[must_use]
    pub fn bytes(value: impl AsRef<[u8]>) -> Self {
        Self::Bytes(value.as_ref().to_vec())
    }

    /// Construct SQL `NULL`.
    #[must_use]
    pub const fn null() -> Self {
        Self::Null
    }

    /// Construct a source error.
    #[must_use]
    pub fn error(message: impl Into<String>) -> Self {
        Self::Error(message.into())
    }
}

impl From<String> for RenewalShopQueryValue {
    fn from(value: String) -> Self {
        Self::Text(value)
    }
}

impl From<&str> for RenewalShopQueryValue {
    fn from(value: &str) -> Self {
        Self::Text(value.to_owned())
    }
}

impl From<Vec<u8>> for RenewalShopQueryValue {
    fn from(value: Vec<u8>) -> Self {
        Self::Bytes(value)
    }
}

impl From<&[u8]> for RenewalShopQueryValue {
    fn from(value: &[u8]) -> Self {
        Self::Bytes(value.to_vec())
    }
}

/// A source-shaped row for the fixed 28-column renewal query.
///
/// The vector retains malformed widths so conversion can return a typed
/// `ColumnCount` error instead of indexing past the supplied row.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RenewalShopQueryRow {
    columns: Vec<RenewalShopQueryValue>,
}

impl RenewalShopQueryRow {
    /// Construct a row while retaining all supplied cells and their order.
    pub fn new<I>(columns: I) -> Self
    where
        I: IntoIterator<Item = RenewalShopQueryValue>,
    {
        Self {
            columns: columns.into_iter().collect(),
        }
    }

    /// Alias for [`Self::new`].
    #[must_use]
    pub fn from_columns<I>(columns: I) -> Self
    where
        I: IntoIterator<Item = RenewalShopQueryValue>,
    {
        Self::new(columns)
    }

    /// Construct and validate a 28-column row.
    ///
    /// # Errors
    ///
    /// Returns [`RenewalShopRowError::ColumnCount`] when `columns` does not
    /// contain exactly [`RENEWAL_SHOP_TABLE_QUERY_COLUMNS`] cells.
    pub fn try_new<I>(columns: I) -> Result<Self, RenewalShopRowError>
    where
        I: IntoIterator<Item = RenewalShopQueryValue>,
    {
        let row = Self::new(columns);
        check_row_width(&row)?;
        Ok(row)
    }

    /// Construct from a statically sized column set.
    #[must_use]
    pub fn from_typed_columns(
        columns: [RenewalShopQueryValue; RENEWAL_SHOP_TABLE_QUERY_COLUMNS],
    ) -> Self {
        Self::new(columns)
    }

    /// Borrow all cells in source-query order.
    #[must_use]
    pub fn columns(&self) -> &[RenewalShopQueryValue] {
        &self.columns
    }

    /// Consume the row and return its cells.
    #[must_use]
    pub fn into_columns(self) -> Vec<RenewalShopQueryValue> {
        self.columns
    }

    /// Return the supplied width, including a malformed width.
    #[must_use]
    pub fn column_count(&self) -> usize {
        self.columns.len()
    }
}

impl From<[RenewalShopQueryValue; RENEWAL_SHOP_TABLE_QUERY_COLUMNS]> for RenewalShopQueryRow {
    fn from(columns: [RenewalShopQueryValue; RENEWAL_SHOP_TABLE_QUERY_COLUMNS]) -> Self {
        Self::from_typed_columns(columns)
    }
}

impl TryFrom<Vec<RenewalShopQueryValue>> for RenewalShopQueryRow {
    type Error = RenewalShopRowError;

    fn try_from(columns: Vec<RenewalShopQueryValue>) -> Result<Self, Self::Error> {
        Self::try_new(columns)
    }
}

