//! SQL-free conversion of the active legacy renewal-shop boot table.
//!
//! The legacy `InitializeShopEXTable` loader in
//! `server/server/db/ClientManagerBoot.cpp` uses one generated 28-column
//! query.  It groups rows in a `std::map<int, TShopTable*>` and copies each
//! joined row into the current item slot.  This module is the corresponding
//! pure projection boundary.  It does not execute SQL, own a connection,
//! choose a boot feature profile, or mutate process/game state.
//!
//! The strict decoder is the default.  It requires complete decimal numeric
//! cells and rejects SQL `NULL`, source errors, numeric overflow, and malformed
//! rows.  [`decode_renewal_shop_query_row_legacy`] is the explicit compatibility
//! decoder.  It models the active x86 `str_to_number` calls, including C
//! whitespace, signs, decimal prefixes, x86 destination casts, embedded-NUL
//! termination, and the fact that NULL/empty/first-NUL input leaves an existing
//! destination unchanged.
//!
//! The legacy source allocates a new `TShopTable`, immediately `memset`s all
//! of its bytes to zero, and then parses into that state.  Consequently a
//! renewal item has zero `pos` and `price_type` unless the query explicitly
//! overwrites them.  This differs from the base-shop constructor defaults.
//! A row with a zero item vnum still writes every supplied field into the
//! current slot, but it does not advance `byItemCount`; a later row can
//! overwrite that same slot.  A NULL/empty item-vnum cell leaves the current
//! vnum unchanged in the legacy policy.  The builder rejects writes once the
//! fixed 40-slot capacity is exhausted instead of reproducing an overrun.
//!
//! Names are copied as raw bytes with the source's fixed 33-byte `memcpy`.
//! A NULL name is a typed error (the legacy pointer dereference is not a safe
//! policy).  For a short raw cell, the unavailable tail is zero-filled; this
//! is the documented safe representation of the legacy over-read.  Embedded
//! NUL bytes are preserved rather than interpreted as a C string.
//!
//! An empty query result is valid and produces an empty
//! `BootSectionKind::RenewalShop` section with the fixed record width.

