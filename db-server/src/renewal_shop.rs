    #[test]
    fn packed_record_keeps_true_zero_wire_fields() {
        let section = build_renewal_shop_section_legacy(&[row_with(
            1,
            b"wire",
            "16909060",
            "84281096",
            "2314",
            "72623859790382856",
            "286397204",
            "21",
        )])
        .expect("wire row");
        let encoded = &section.data[..RENEWAL_SHOP_TABLE_WIRE_SIZE];
        assert_eq!(&encoded[0..4], &[1, 0, 0, 0]);
        assert_eq!(&encoded[4..8], &[4, 3, 2, 1]);
        // The table count byte precedes the first item; item vnum/count then
        // begin at offsets 9 and 13 in the packed source layout.
        assert_eq!(encoded[8], 1);
        assert_eq!(&encoded[9..13], &[8, 7, 6, 5]);
        assert_eq!(&encoded[13..15], &[10, 9]);
        assert_eq!(&encoded[15..18], &[0, 0, 0]);
        assert_eq!(&encoded[18..26], &[8, 7, 6, 5, 4, 3, 2, 1]);
        assert_eq!(&encoded[26..41], &[0; 15]);
        let record = record_at(&section, 0);
        assert_eq!(record.items[0].vnum, 0x0506_0708);
        assert_eq!(record.items[0].count, 0x090a);
        assert_eq!(record.items[0].pos, ShopItemPosition::new(0, 0));
        assert_eq!(record.items[0].price, 0x0102_0304_0506_0708);
        assert_eq!(record.items[0].price_type, 21); // The query supplied this byte.
    }
