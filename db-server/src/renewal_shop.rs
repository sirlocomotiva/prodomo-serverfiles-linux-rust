/// A source adapter for the fixed renewal-shop query.
///
/// Implementations are SQL-free from this module's point of view.  They may
/// receive rows from any caller-owned acquisition boundary, but this module
/// never opens a connection, selects a profile, or mutates a cache.
pub trait RenewalShopTableRowSource {
    /// Source-specific acquisition error.
    type Error;

    /// Fetch all joined rows in source order.
    ///
    /// # Errors
    ///
    /// Returns the source adapter's acquisition error when row retrieval fails.
    fn query_rows(
        &self,
        query: &RenewalShopTableQuery,
    ) -> Result<Vec<RenewalShopQueryRow>, Self::Error>;
}

impl<F, E> RenewalShopTableRowSource for F
where
    F: Fn(&RenewalShopTableQuery) -> Result<Vec<RenewalShopQueryRow>, E>,
{
    type Error = E;

    fn query_rows(
        &self,
        query: &RenewalShopTableQuery,
    ) -> Result<Vec<RenewalShopQueryRow>, Self::Error> {
        self(query)
    }
}

/// Compatibility name for the row-source trait.
pub use RenewalShopTableRowSource as RenewalShopRowSource;

/// A loader configured with the source statement and output limits.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct RenewalShopTableLoader {
    limits: RenewalShopSectionLimits,
}

impl RenewalShopTableLoader {
    /// Construct a loader with default limits.
    #[must_use]
    pub const fn new() -> Self {
        Self {
            limits: RenewalShopSectionLimits {
                max_records: RENEWAL_SHOP_TABLE_MAX_RECORDS,
                max_data_bytes: RENEWAL_SHOP_TABLE_MAX_SECTION_BYTES,
            },
        }
    }

    /// Construct a loader with a caller-selected group limit.
    #[must_use]
    pub const fn with_limit(max_records: usize) -> Self {
        Self {
            limits: RenewalShopSectionLimits::new(max_records),
        }
    }

    /// Construct a loader with explicit limits.
    #[must_use]
    pub const fn with_limits(limits: RenewalShopSectionLimits) -> Self {
        Self { limits }
    }

    /// Alias for [`Self::with_limits`].
    #[must_use]
    pub const fn from_limits(limits: RenewalShopSectionLimits) -> Self {
        Self::with_limits(limits)
    }

    /// Construct a loader with the default section limits.
    #[must_use]
    pub fn default_with_limits() -> Self {
        Self::new()
    }

    /// Borrow the exact statement used by this loader.
    #[must_use]
    pub const fn query(&self) -> RenewalShopTableQuery {
        RenewalShopTableQuery::new()
    }

    /// Borrow configured limits.
    #[must_use]
    pub const fn limits(&self) -> RenewalShopSectionLimits {
        self.limits
    }

    /// Return the exact source statement text.
    #[must_use]
    pub const fn statement(&self) -> &'static str {
        RENEWAL_SHOP_TABLE_QUERY
    }

    /// Alias for [`Self::statement`].
    #[must_use]
    pub const fn as_str(&self) -> &'static str {
        RENEWAL_SHOP_TABLE_QUERY
    }

    /// Return the defensive raw joined-source-row cap for this loader.
    ///
    /// The result is `None` when the distinct-shop limit cannot fit the boot
    /// `u16` count. This is an acquisition bound, not a schema guarantee that
    /// every source row belongs to a distinct shop.
    #[must_use]
    pub const fn source_row_limit(&self) -> Option<usize> {
        renewal_shop_source_row_limit(self.limits.max_records)
    }

    /// Project caller-supplied rows directly with the strict policy.
    ///
    /// # Errors
    ///
    /// Returns [`RenewalShopSectionError`] for malformed rows, fixed-capacity
    /// violations, count or data-size overflow, allocation failure, or limit
    /// failure.
    pub fn load(
        &self,
        rows: &[RenewalShopQueryRow],
    ) -> Result<BootSection, RenewalShopSectionError> {
        build_renewal_shop_section_with_limits(rows, self.limits)
    }

    /// Alias for [`Self::load`].
    ///
    /// # Errors
    ///
    /// Returns the same errors as [`Self::load`].
    pub fn build(
        &self,
        rows: &[RenewalShopQueryRow],
    ) -> Result<BootSection, RenewalShopSectionError> {
        self.load(rows)
    }

    /// Project caller-supplied rows with the named legacy policy.
    ///
    /// # Errors
    ///
    /// Returns the same row, capacity, and limit errors as [`Self::load`].
    pub fn load_legacy(
        &self,
        rows: &[RenewalShopQueryRow],
    ) -> Result<BootSection, RenewalShopSectionError> {
        build_renewal_shop_section_legacy_with_limits(rows, self.limits)
    }

    /// Load an injected source with the strict policy.
    ///
    /// # Errors
    ///
    /// Returns [`RenewalShopTableLoadError`] for source or section failure.
    pub fn load_source<S>(
        &self,
        source: &S,
    ) -> Result<BootSection, RenewalShopTableLoadError<S::Error>>
    where
        S: RenewalShopTableRowSource,
    {
        self.load_section(source)
    }

    /// Load and strictly project rows from an injected source.
    ///
    /// # Errors
    ///
    /// Returns [`RenewalShopTableLoadError::Source`] for source failures and
    /// [`RenewalShopTableLoadError::Rows`] for projection failures.
    pub fn load_section<S>(
        &self,
        source: &S,
    ) -> Result<BootSection, RenewalShopTableLoadError<S::Error>>
    where
        S: RenewalShopTableRowSource,
    {
        let rows = source
            .query_rows(&self.query())
            .map_err(RenewalShopTableLoadError::Source)?;
        build_renewal_shop_section_with_limits(&rows, self.limits)
            .map_err(RenewalShopTableLoadError::Rows)
    }

    /// Load and project rows using the explicitly named legacy policy.
    ///
    /// # Errors
    ///
    /// Returns [`RenewalShopTableLoadError::Source`] for source failures and
    /// [`RenewalShopTableLoadError::Rows`] for projection failures.
    pub fn load_section_legacy<S>(
        &self,
        source: &S,
    ) -> Result<BootSection, RenewalShopTableLoadError<S::Error>>
    where
        S: RenewalShopTableRowSource,
    {
        let rows = source
            .query_rows(&self.query())
            .map_err(RenewalShopTableLoadError::Source)?;
        build_renewal_shop_section_legacy_with_limits(&rows, self.limits)
            .map_err(RenewalShopTableLoadError::Rows)
    }
}

impl Default for RenewalShopTableLoader {
    fn default() -> Self {
        Self::new()
    }
}

/// A source or projection error from the injected loader boundary.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum RenewalShopTableLoadError<E> {
    /// The caller-owned row source failed.
    Source(E),
    /// The source returned rows that could not be projected.
    Rows(RenewalShopSectionError),
}

impl<E> fmt::Display for RenewalShopTableLoadError<E>
where
    E: fmt::Display,
{
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Source(error) => write!(formatter, "renewal-shop source failed: {error}"),
            Self::Rows(error) => write!(formatter, "renewal-shop projection failed: {error}"),
        }
    }
}

impl<E> Error for RenewalShopTableLoadError<E>
where
    E: Error + 'static,
{
    fn source(&self) -> Option<&(dyn Error + 'static)> {
        match self {
            Self::Source(error) => Some(error),
            Self::Rows(error) => Some(error),
        }
    }
}

