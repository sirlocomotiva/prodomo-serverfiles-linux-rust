/// Strict-policy spelling of [`decode_renewal_shop_query_row`].
///
/// # Errors
///
/// Returns a typed [`RenewalShopRowError`] for a wrong row width, SQL NULL,
/// invalid numeric text, numeric overflow, or malformed raw name.
pub fn decode_renewal_shop_query_row_strict(
    row: &RenewalShopQueryRow,
) -> Result<DecodedRenewalShopRow, RenewalShopRowError> {
    check_row_width(row)?;
    let columns = row.columns();
    let shop_vnum = strict_i32(&columns[0], 0)?;
    let shop_name = copy_raw_name(&columns[1], 1)?;
    let npc_vnum = Some(strict_u32(&columns[2], 2)?);
    let item = strict_row_item(row)?;
    Ok(DecodedRenewalShopRow {
        shop_vnum,
        shop_name,
        npc_vnum,
        item,
    })
}

/// Decode one row using the explicitly named legacy x86 conversion policy.
///
/// # Errors
///
/// Returns a typed [`RenewalShopRowError`] for a wrong row width, source cell
/// error, or malformed raw name. Numeric NULLs and unparsable-but-nonempty
/// legacy cells are represented by the stateful `Option` fields.
///
/// Numeric `NULL`, empty, and first-NUL cells produce `None` updates.  A
/// non-empty cell, including whitespace or an invalid prefix, produces a
/// value according to the C parser.  The latter is why this API does not
/// return a fully materialized item: `None` is stateful destination data.
pub fn decode_renewal_shop_query_row_legacy(
    row: &RenewalShopQueryRow,
) -> Result<DecodedRenewalShopRow, RenewalShopRowError> {
    check_row_width(row)?;
    let columns = row.columns();
    // The C++ local `iShopVnum` is initialized to zero and
    // `str_to_number` leaves it unchanged for NULL/empty/first-NUL input.
    // Consequently those rows are grouped under signed key zero.
    let shop_vnum = legacy_optional_i32(&columns[0], 0)?.unwrap_or(0);
    let shop_name = copy_raw_name(&columns[1], 1)?;
    let npc_vnum = legacy_optional_u32(&columns[2], 2)?;
    let item = legacy_row_item(row)?;
    Ok(DecodedRenewalShopRow {
        shop_vnum,
        shop_name,
        npc_vnum,
        item,
    })
}

/// Decode one row with an explicit policy.
