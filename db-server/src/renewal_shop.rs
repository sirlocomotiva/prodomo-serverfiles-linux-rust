/// A typed error in one strict or legacy renewal-shop row.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum RenewalShopRowError {
    /// The row did not contain exactly 28 cells.
    ColumnCount {
        /// Required source width.
        expected: usize,
        /// Supplied source width.
        actual: usize,
    },
    /// A required cell was SQL `NULL`.
    Null {
        /// Zero-based query column.
        column: usize,
    },
    /// A source adapter could not obtain or convert a cell.
    Source {
        /// Zero-based query column.
        column: usize,
        /// Original diagnostic.
        message: String,
    },
    /// A non-NULL value was not a complete strict decimal integer.
    InvalidNumber {
        /// Zero-based query column.
        column: usize,
        /// Bounded lossy diagnostic.
        value: String,
        /// Target integer type.
        target: &'static str,
    },
    /// A syntactically valid integer did not fit its strict target type.
    NumberOverflow {
        /// Zero-based query column.
        column: usize,
        /// Bounded lossy diagnostic.
        value: String,
        /// Target integer type.
        target: &'static str,
    },
}

impl fmt::Display for RenewalShopRowError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::ColumnCount { expected, actual } => write!(
                formatter,
                "renewal-shop query row has {actual} columns; expected {expected}"
            ),
            Self::Null { column } => write!(
                formatter,
                "renewal-shop query column {} is NULL",
                renewal_shop_query_column_name(*column)
            ),
            Self::Source { column, message } => write!(
                formatter,
                "renewal-shop query column {} could not be read: {}",
                renewal_shop_query_column_name(*column),
                bounded_display(message)
            ),
            Self::InvalidNumber {
                column,
                value,
                target,
            } => write!(
                formatter,
                "renewal-shop query column {} value {:?} is not a strict {}",
                renewal_shop_query_column_name(*column),
                value,
                target
            ),
            Self::NumberOverflow {
                column,
                value,
                target,
            } => write!(
                formatter,
                "renewal-shop query column {} value {:?} overflows {}",
                renewal_shop_query_column_name(*column),
                value,
                target
            ),
        }
    }
}

impl Error for RenewalShopRowError {}

/// Per-field writes produced by one decoded row.
///
/// `None` is meaningful in the legacy policy: `str_to_number` did not write
/// its destination because the cell was SQL NULL, empty, or began with NUL.
/// `Some(0)` is different: it explicitly overwrites the field with zero.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RenewalShopItemUpdate {
    /// Item vnum write.
    pub vnum: Option<u32>,
    /// Item count write.
    pub count: Option<u16>,
    /// Item price write (`ENABLE_REMOVE_LIMIT_GOLD` is active).
    pub price: Option<u64>,
    /// Price-item vnum write.
    pub price_vnum: Option<u32>,
    /// Price selector write.
    pub price_type: Option<u8>,
    /// Socket writes.
    pub sockets: [Option<i32>; SHOP_ITEM_SOCKET_MAX_NUM],
    /// Attribute writes, in source order.
    pub attrs: [RenewalShopAttributeUpdate; SHOP_ITEM_ATTRIBUTE_MAX_NUM],
}

/// One attribute pair's optional writes.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct RenewalShopAttributeUpdate {
    /// `bType` write.
    pub attr_type: Option<u8>,
    /// `sValue` write.
    pub value: Option<i16>,
}

impl RenewalShopAttributeUpdate {
    /// Construct two explicit writes.
    #[must_use]
    pub const fn new(attr_type: Option<u8>, value: Option<i16>) -> Self {
        Self { attr_type, value }
    }
}

impl RenewalShopItemUpdate {
    /// Construct an update with all fields explicitly written.
    #[must_use]
    pub fn written(
        vnum: u32,
        count: u16,
        price: u64,
        price_vnum: u32,
        price_type: u8,
        sockets: [i32; SHOP_ITEM_SOCKET_MAX_NUM],
        attrs: [ShopItemAttribute; SHOP_ITEM_ATTRIBUTE_MAX_NUM],
    ) -> Self {
        Self {
            vnum: Some(vnum),
            count: Some(count),
            price: Some(price),
            price_vnum: Some(price_vnum),
            price_type: Some(price_type),
            sockets: sockets.map(Some),
            attrs: attrs.map(|attr| {
                RenewalShopAttributeUpdate::new(Some(attr.attr_type), Some(attr.value))
            }),
        }
    }
}

