/// A checked renewal-shop section error.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum RenewalShopSectionError {
    /// More distinct shops were supplied than the caller permits.
    TooManyShops {
        /// Number of distinct shop groups.
        count: usize,
        /// Configured maximum.
        maximum: usize,
    },
    /// The injected source exceeded a defensive acquisition bound.
    TooManySourceRows {
        /// Number of source rows supplied.
        count: usize,
        /// Configured maximum.
        maximum: usize,
    },
    /// Distinct shop count cannot be represented by the boot `u16` count.
    CountOverflow {
        /// Number of distinct shop groups.
        count: usize,
    },
    /// Fixed record width cannot be represented by the boot `u16` width.
    RecordSizeOverflow {
        /// Fixed record width.
        size: usize,
    },
    /// Packed data-size arithmetic overflowed `usize`.
    DataSizeOverflow {
        /// Shop count used in the multiplication.
        count: usize,
    },
    /// Output or group storage could not reserve a checked bound.
    AllocationFailed {
        /// Requested allocation size or item count.
        requested: usize,
    },
    /// Packed data exceeds the caller's byte limit.
    DataTooLarge {
        /// Required packed data length.
        length: usize,
        /// Configured byte limit.
        maximum: usize,
    },
    /// A shop attempted to address more than its fixed 40-item capacity.
    ItemCapacityOverflow {
        /// Signed source map key.
        shop_vnum: i32,
        /// Number of items after the attempted write.
        count: usize,
        /// Fixed source capacity.
        maximum: usize,
    },
    /// Protocol encoding returned an unexpected record width.
    RecordSizeMismatch {
        /// Zero-based output shop index.
        index: usize,
        /// Required packed width.
        expected: usize,
        /// Actual encoded width.
        actual: usize,
    },
    /// A source row could not be decoded.
    Row {
        /// Zero-based source row index.
        index: usize,
        /// Row error.
        source: RenewalShopRowError,
    },
}

impl fmt::Display for RenewalShopSectionError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::TooManyShops { count, maximum } => write!(
                formatter,
                "renewal-shop query produced {count} distinct shops; maximum is {maximum}"
            ),
            Self::TooManySourceRows { count, maximum } => write!(
                formatter,
                "renewal-shop query produced {count} source rows; maximum is {maximum}"
            ),
            Self::CountOverflow { count } => {
                write!(formatter, "renewal-shop count {count} does not fit u16")
            }
            Self::RecordSizeOverflow { size } => write!(
                formatter,
                "renewal-shop record size {size} does not fit u16"
            ),
            Self::DataSizeOverflow { count } => write!(
                formatter,
                "renewal-shop data size overflows usize for {count} records"
            ),
            Self::AllocationFailed { requested } => write!(
                formatter,
                "renewal-shop allocation of {requested} units failed"
            ),
            Self::DataTooLarge { length, maximum } => write!(
                formatter,
                "renewal-shop data length {length} exceeds maximum {maximum}"
            ),
            Self::ItemCapacityOverflow {
                shop_vnum,
                count,
                maximum,
            } => write!(
                formatter,
                "renewal-shop {shop_vnum} attempted item {count}; fixed maximum is {maximum}"
            ),
            Self::RecordSizeMismatch {
                index,
                expected,
                actual,
            } => write!(
                formatter,
                "renewal-shop record {index} encoded to {actual} bytes; expected {expected}"
            ),
            Self::Row { index, source } => {
                write!(formatter, "renewal-shop row {index}: {source}")
            }
        }
    }
}

impl Error for RenewalShopSectionError {
    fn source(&self) -> Option<&(dyn Error + 'static)> {
        match self {
            Self::Row { source, .. } => Some(source),
            _ => None,
        }
    }
}

struct RenewalShopGroup {
    npc_vnum: u32,
    shop_name: [u8; RENEWAL_SHOP_NAME_BYTES],
    items: Vec<ShopItemRecord>,
    item_count: usize,
}

impl RenewalShopGroup {
    fn new() -> Self {
        Self {
            npc_vnum: 0,
            shop_name: [0; RENEWAL_SHOP_NAME_BYTES],
            // The pending slot is already part of the source's zeroed
            // destination.  Keeping it in the vector makes repeated writes
            // stateful without materializing 40 slots per group.
            items: vec![ShopItemRecord::zeroed_renewal_slot()],
            item_count: 0,
        }
    }

    fn apply(
        &mut self,
        shop_vnum: i32,
        decoded: &DecodedRenewalShopRow,
    ) -> Result<(), RenewalShopSectionError> {
        if self.item_count >= RENEWAL_SHOP_ITEM_MAX_NUM {
            return Err(RenewalShopSectionError::ItemCapacityOverflow {
                shop_vnum,
                count: self.item_count + 1,
                maximum: RENEWAL_SHOP_ITEM_MAX_NUM,
            });
        }
        let index = self.item_count;
        if self.items.len() <= index {
            let additional = index + 1 - self.items.len();
            self.items.try_reserve(additional).map_err(|_| {
                RenewalShopSectionError::AllocationFailed {
                    requested: additional,
                }
            })?;
            self.items
                .extend((self.items.len()..=index).map(|_| ShopItemRecord::zeroed_renewal_slot()));
        }

        self.shop_name = decoded.shop_name;
        if let Some(npc_vnum) = decoded.npc_vnum {
            self.npc_vnum = npc_vnum;
        }

        let item = &mut self.items[index];
        if let Some(vnum) = decoded.item.vnum {
            item.vnum = vnum;
        }
        if let Some(count) = decoded.item.count {
            item.count = count;
        }
        if let Some(price) = decoded.item.price {
            item.price = price;
        }
        if let Some(price_vnum) = decoded.item.price_vnum {
            item.price_vnum = price_vnum;
        }
        if let Some(price_type) = decoded.item.price_type {
            item.price_type = price_type;
        }
        for (slot, value) in item.sockets.iter_mut().zip(decoded.item.sockets) {
            if let Some(value) = value {
                *slot = value;
            }
        }
        for (slot, value) in item.attrs.iter_mut().zip(decoded.item.attrs) {
            if let Some(attr_type) = value.attr_type {
                slot.attr_type = attr_type;
            }
            if let Some(value) = value.value {
                slot.value = value;
            }
        }

        // This is intentionally the resulting slot vnum, not the raw cell.
        // It preserves the source behavior for a zero/NULL vnum row.
        if item.vnum != 0 {
            self.item_count += 1;
        }
        Ok(())
    }
}

fn validate_section_size(
    count: usize,
    limits: RenewalShopSectionLimits,
) -> Result<(u16, u16, usize), RenewalShopSectionError> {
    if count > limits.max_records {
        return Err(RenewalShopSectionError::TooManyShops {
            count,
            maximum: limits.max_records,
        });
    }
    let wire_count =
        u16::try_from(count).map_err(|_| RenewalShopSectionError::CountOverflow { count })?;
    let record_size = u16::try_from(RENEWAL_SHOP_TABLE_WIRE_SIZE).map_err(|_| {
        RenewalShopSectionError::RecordSizeOverflow {
            size: RENEWAL_SHOP_TABLE_WIRE_SIZE,
        }
    })?;
    let data_len = RENEWAL_SHOP_TABLE_WIRE_SIZE
        .checked_mul(count)
        .ok_or(RenewalShopSectionError::DataSizeOverflow { count })?;
    if data_len > limits.max_data_bytes {
        return Err(RenewalShopSectionError::DataTooLarge {
            length: data_len,
            maximum: limits.max_data_bytes,
        });
    }
    Ok((wire_count, record_size, data_len))
}

/// Validate count, record-width, and packed-data arithmetic without decoding
/// rows or allocating output.
///
/// # Errors
///
/// Returns [`RenewalShopSectionError`] for configured limits, `u16` overflow,
/// or checked `usize` overflow.
pub fn checked_renewal_shop_section_size(
    count: usize,
    limits: RenewalShopSectionLimits,
) -> Result<(u16, u16, usize), RenewalShopSectionError> {
    validate_section_size(count, limits)
}

fn append_projection(
    rows: &[RenewalShopQueryRow],
    limits: RenewalShopSectionLimits,
    legacy: bool,
) -> Result<BootSection, RenewalShopSectionError> {
    // A repeated zero-vnum row can be legal source input.  We do not derive a
    // `max_records * 40` bound before processing, so capacity errors retain
    // their source-order meaning.  The global ceiling is only a last-resort
    // guard against an injected slice that cannot plausibly be a query result.
    if rows.len() > RENEWAL_SHOP_TABLE_MAX_SOURCE_ROWS {
        return Err(RenewalShopSectionError::TooManySourceRows {
            count: rows.len(),
            maximum: RENEWAL_SHOP_TABLE_MAX_SOURCE_ROWS,
        });
    }

    let mut groups: BTreeMap<i32, RenewalShopGroup> = BTreeMap::new();
    for (index, row) in rows.iter().enumerate() {
        let decoded = if legacy {
            decode_renewal_shop_query_row_legacy(row)
        } else {
            decode_renewal_shop_query_row_strict(row)
        }
        .map_err(|source| RenewalShopSectionError::Row { index, source })?;

        if !groups.contains_key(&decoded.shop_vnum) && groups.len() >= limits.max_records {
            return Err(RenewalShopSectionError::TooManyShops {
                count: groups.len() + 1,
                maximum: limits.max_records,
            });
        }
        let group = groups
            .entry(decoded.shop_vnum)
            .or_insert_with(RenewalShopGroup::new);
        group.apply(decoded.shop_vnum, &decoded)?;
    }

    // Treat the usual `max_records * 40` bound as an acquisition policy only
    // after source-order item-capacity handling.  It protects a custom
    // adapter from unbounded duplicate input while leaving zero-vnum semantics
    // observable in the normal case.
    if limits.max_records > 0 {
        let maximum = renewal_shop_source_row_limit(limits.max_records)
            .unwrap_or(RENEWAL_SHOP_TABLE_MAX_SOURCE_ROWS);
        if rows.len() > maximum {
            return Err(RenewalShopSectionError::TooManySourceRows {
                count: rows.len(),
                maximum,
            });
        }
    }

    let (count, record_size, data_len) = validate_section_size(groups.len(), limits)?;
    let mut data = Vec::new();
    data.try_reserve_exact(data_len)
        .map_err(|_| RenewalShopSectionError::AllocationFailed {
            requested: data_len,
        })?;

    for (index, (shop_vnum, group)) in groups.into_iter().enumerate() {
        let mut record = ShopTableRecord::zeroed_renewal_shop();
        record.vnum = u32::from_le_bytes(shop_vnum.to_le_bytes());
        record.npc_vnum = group.npc_vnum;
        record.shop_name = group.shop_name;
        record.item_count = u8::try_from(group.item_count).map_err(|_| {
            RenewalShopSectionError::ItemCapacityOverflow {
                shop_vnum,
                count: group.item_count,
                maximum: RENEWAL_SHOP_ITEM_MAX_NUM,
            }
        })?;
        for (slot, item) in record.items.iter_mut().zip(group.items) {
            *slot = item;
        }
        let encoded = RecordCodec::encode(&record);
        if encoded.len() != RENEWAL_SHOP_TABLE_WIRE_SIZE {
            return Err(RenewalShopSectionError::RecordSizeMismatch {
                index,
                expected: RENEWAL_SHOP_TABLE_WIRE_SIZE,
                actual: encoded.len(),
            });
        }
        data.extend_from_slice(&encoded);
    }

    debug_assert_eq!(data.len(), data_len);
    Ok(BootSection {
        kind: BootSectionKind::RenewalShop,
        record_size,
        count,
        data,
    })
}

