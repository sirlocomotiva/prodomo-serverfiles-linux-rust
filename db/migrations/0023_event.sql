-- The event calendar (ledger section 387).
--
-- Legacy's `event` table (`legacy/sql/schema/player.sql:120-129`), which the DB server reads
-- at boot (`SELECT id, type, UNIX_TIMESTAMP(start), UNIX_TIMESTAMP(end), value0, value1,
-- completed FROM event ORDER BY start`, `D/ClientManagerBoot.cpp:1696`) and every game
-- process keeps in `CEventManager::m_mapEvent` (`G/event_manager.cpp:506-561`).
--
-- The id is the `dwID` the client sees, so it stays a 32-bit integer. `type` names an
-- `EEventTypes` member; `EVENT_TYPE_NONE`, which `Initialize` skips, is refused here. Both
-- times reach the client as a 32-bit `long`, and `Initialize` skips a zero one, so each lies
-- between the first second after the epoch and 2038-01-19.
CREATE TABLE event (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    type text NOT NULL CHECK (type IN (
        'EVENT_TYPE_EXPERIENCE', 'EVENT_TYPE_ITEM_DROP', 'EVENT_TYPE_BOSS', 'EVENT_TYPE_METIN',
        'EVENT_TYPE_MINING', 'EVENT_TYPE_GOLD_FROG', 'EVENT_TYPE_MOONLIGHT',
        'EVENT_TYPE_HEXEGONAL_CHEST', 'EVENT_TYPE_FISHING', 'EVENT_TYPE_HIDE_AND_SEEK',
        'EVENT_TYPE_OX', 'EVENT_TYPE_TANAKA', 'EVENT_TYPE_SIEGE_WAR', 'EVENT_TYPE_KINGDOM_WAR'
    )),
    start_at timestamptz NOT NULL
        CHECK (start_at BETWEEN to_timestamp(1) AND to_timestamp(2147483647)),
    end_at timestamptz NOT NULL
        CHECK (end_at BETWEEN to_timestamp(1) AND to_timestamp(2147483647)),
    value0 integer NOT NULL DEFAULT 0,
    value1 integer NOT NULL DEFAULT 0,
    completed boolean NOT NULL DEFAULT false
);
