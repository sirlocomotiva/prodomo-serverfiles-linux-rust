fn bounded_display(value: &str) -> String {
    const LIMIT: usize = 96;
    if value.chars().count() <= LIMIT {
        return value.to_owned();
    }
    let mut out = value.chars().take(LIMIT).collect::<String>();
    out.push('…');
    out
}

fn bounded_value(bytes: &[u8]) -> String {
    const LIMIT: usize = 96;
    let text = String::from_utf8_lossy(bytes);
    if text.chars().count() <= LIMIT {
        return text.into_owned();
    }
    let mut out = text.chars().take(LIMIT).collect::<String>();
    out.push('…');
    out
}

fn check_row_width(row: &RenewalShopQueryRow) -> Result<(), RenewalShopRowError> {
    let actual = row.column_count();
    if actual == RENEWAL_SHOP_TABLE_QUERY_COLUMNS {
        Ok(())
    } else {
        Err(RenewalShopRowError::ColumnCount {
            expected: RENEWAL_SHOP_TABLE_QUERY_COLUMNS,
            actual,
        })
    }
}

fn raw_cell_bytes(
    value: &RenewalShopQueryValue,
    column: usize,
) -> Result<&[u8], RenewalShopRowError> {
    match value {
        RenewalShopQueryValue::Text(text) => Ok(text.as_bytes()),
        RenewalShopQueryValue::Bytes(bytes) => Ok(bytes.as_slice()),
        RenewalShopQueryValue::Null => Err(RenewalShopRowError::Null { column }),
        RenewalShopQueryValue::Error(message) => Err(RenewalShopRowError::Source {
            column,
            message: message.clone(),
        }),
    }
}

fn copy_raw_name(
    value: &RenewalShopQueryValue,
    column: usize,
) -> Result<[u8; RENEWAL_SHOP_NAME_BYTES], RenewalShopRowError> {
    let bytes = raw_cell_bytes(value, column)?;
    let mut out = [0_u8; RENEWAL_SHOP_NAME_BYTES];
    let copy_len = bytes.len().min(RENEWAL_SHOP_NAME_BYTES);
    out[..copy_len].copy_from_slice(&bytes[..copy_len]);
    Ok(out)
}

fn strict_decimal_parts(
    bytes: &[u8],
    column: usize,
    target: &'static str,
    signed: bool,
) -> Result<(bool, u128), RenewalShopRowError> {
    if bytes.is_empty() || bytes[0] == 0 {
        return Err(RenewalShopRowError::InvalidNumber {
            column,
            value: bounded_value(bytes),
            target,
        });
    }
    let mut offset = 0;
    let mut negative = false;
    if signed {
        match bytes[0] {
            b'-' => {
                negative = true;
                offset = 1;
            }
            b'+' => {
                return Err(RenewalShopRowError::InvalidNumber {
                    column,
                    value: bounded_value(bytes),
                    target,
                });
            }
            _ => {}
        }
    }
    if offset == bytes.len() {
        return Err(RenewalShopRowError::InvalidNumber {
            column,
            value: bounded_value(bytes),
            target,
        });
    }
    let mut magnitude = 0_u128;
    for &byte in &bytes[offset..] {
        if byte == 0 || !byte.is_ascii_digit() {
            return Err(RenewalShopRowError::InvalidNumber {
                column,
                value: bounded_value(bytes),
                target,
            });
        }
        let digit = u128::from(byte - b'0');
        magnitude = match magnitude
            .checked_mul(10)
            .and_then(|value| value.checked_add(digit))
        {
            Some(value) => value,
            None => {
                return Err(RenewalShopRowError::NumberOverflow {
                    column,
                    value: bounded_value(bytes),
                    target,
                })
            }
        };
    }
    Ok((negative, magnitude))
}

#[allow(clippy::cast_possible_truncation)]
fn strict_i32(value: &RenewalShopQueryValue, column: usize) -> Result<i32, RenewalShopRowError> {
    let bytes = raw_cell_bytes(value, column)?;
    let (negative, magnitude) = strict_decimal_parts(bytes, column, "i32", true)?;
    let max = if negative {
        1_u128 << 31
    } else {
        (1_u128 << 31) - 1
    };
    if magnitude > max {
        return Err(RenewalShopRowError::NumberOverflow {
            column,
            value: bounded_value(bytes),
            target: "i32",
        });
    }
    if negative {
        if magnitude == (1_u128 << 31) {
            Ok(i32::MIN)
        } else {
            Ok(-(magnitude as i32))
        }
    } else {
        Ok(magnitude as i32)
    }
}

#[allow(clippy::cast_possible_truncation)]
fn strict_u32(value: &RenewalShopQueryValue, column: usize) -> Result<u32, RenewalShopRowError> {
    let bytes = raw_cell_bytes(value, column)?;
    let (negative, magnitude) = strict_decimal_parts(bytes, column, "u32", false)?;
    if negative || magnitude > u128::from(u32::MAX) {
        return Err(RenewalShopRowError::NumberOverflow {
            column,
            value: bounded_value(bytes),
            target: "u32",
        });
    }
    Ok(magnitude as u32)
}

