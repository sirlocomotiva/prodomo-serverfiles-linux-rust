/// source behavior, so this is intentionally a global ceiling rather than a
/// per-shop `40 * groups` claim.
pub const RENEWAL_SHOP_TABLE_MAX_SOURCE_ROWS: usize =
    RENEWAL_SHOP_TABLE_MAX_RECORDS * RENEWAL_SHOP_ITEM_MAX_NUM;

/// Return a source-row ceiling for a configured distinct-shop limit.
///
/// This helper is advisory for acquisition adapters.  It does not reject
/// repeated zero-vnum rows when a smaller caller limit is selected; the pure
/// builder applies its fixed-capacity check independently.
#[must_use]
pub const fn renewal_shop_source_row_limit(max_records: usize) -> Option<usize> {
    if max_records > RENEWAL_SHOP_TABLE_MAX_RECORDS {
        None
    } else {
        Some(max_records * RENEWAL_SHOP_ITEM_MAX_NUM)
    }
}

