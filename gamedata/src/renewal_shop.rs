fn strict_row_item(
    row: &RenewalShopQueryRow,
) -> Result<RenewalShopItemUpdate, RenewalShopRowError> {
    let columns = row.columns();
    // Keep conversion order aligned with InitializeShopEXTable's col++ walk.
    // This also makes the first typed error deterministic when several cells
    // are malformed.
    let vnum = strict_u32(&columns[3], 3)?;
    let count = strict_u16(&columns[4], 4)?;
    let price = strict_u64(&columns[5], 5)?;
    let price_vnum = strict_u32(&columns[6], 6)?;
    let price_type = strict_u8(&columns[7], 7)?;
    let sockets = [
        strict_i32(&columns[8], 8)?,
        strict_i32(&columns[9], 9)?,
        strict_i32(&columns[10], 10)?,
        strict_i32(&columns[11], 11)?,
        strict_i32(&columns[12], 12)?,
        strict_i32(&columns[13], 13)?,
    ];
    let mut attrs =
        [RenewalShopAttributeUpdate::new(Some(0), Some(0)); SHOP_ITEM_ATTRIBUTE_MAX_NUM];
    for (index, attribute) in attrs.iter_mut().enumerate() {
        let column = 14 + index * 2;
        *attribute = RenewalShopAttributeUpdate::new(
            Some(strict_u8(&columns[column], column)?),
            Some(strict_i16(&columns[column + 1], column + 1)?),
        );
    }
    Ok(RenewalShopItemUpdate {
        vnum: Some(vnum),
        count: Some(count),
        price: Some(price),
        price_vnum: Some(price_vnum),
        price_type: Some(price_type),
        sockets: sockets.map(Some),
        attrs,
    })
}

fn legacy_row_item(
    row: &RenewalShopQueryRow,
) -> Result<RenewalShopItemUpdate, RenewalShopRowError> {
    let columns = row.columns();
    // Preserve the source's scalar -> socket -> attribute read order.
    let vnum = legacy_optional_u32(&columns[3], 3)?;
    let count = legacy_optional_u16(&columns[4], 4)?;
    let price = legacy_optional_u64(&columns[5], 5)?;
    let price_vnum = legacy_optional_u32(&columns[6], 6)?;
    let price_type = legacy_optional_u8(&columns[7], 7)?;
    let sockets = [
        legacy_optional_i32(&columns[8], 8)?,
        legacy_optional_i32(&columns[9], 9)?,
        legacy_optional_i32(&columns[10], 10)?,
        legacy_optional_i32(&columns[11], 11)?,
        legacy_optional_i32(&columns[12], 12)?,
        legacy_optional_i32(&columns[13], 13)?,
    ];
    let mut attrs = [RenewalShopAttributeUpdate::new(None, None); SHOP_ITEM_ATTRIBUTE_MAX_NUM];
    for (index, attribute) in attrs.iter_mut().enumerate() {
        let column = 14 + index * 2;
        *attribute = RenewalShopAttributeUpdate::new(
            legacy_optional_u8(&columns[column], column)?,
            legacy_optional_i16(&columns[column + 1], column + 1)?,
        );
    }
    Ok(RenewalShopItemUpdate {
        vnum,
        count,
        price,
        price_vnum,
        price_type,
        sockets,
        attrs,
    })
}

/// A concrete item value materialized from a strict row or from a caller-made
/// update.  The builder uses [`RenewalShopItemUpdate`] instead, because legacy
/// NULL cells can omit individual writes.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RenewalShopDecodedItem {
    /// Item vnum.
    pub vnum: u32,
    /// Item count.
    pub count: u16,
    /// Item price.
    pub price: u64,
    /// Price-item vnum.
    pub price_vnum: u32,
    /// Price selector; the source does not restrict its range.
    pub price_type: u8,
    /// Socket values.
    pub sockets: [i32; SHOP_ITEM_SOCKET_MAX_NUM],
    /// Attribute values.
    pub attrs: [ShopItemAttribute; SHOP_ITEM_ATTRIBUTE_MAX_NUM],
}

impl RenewalShopDecodedItem {
    /// Materialize an update over an all-zero renewal slot.
    #[must_use]
    pub fn from_update(update: &RenewalShopItemUpdate) -> Self {
        let mut sockets = [0_i32; SHOP_ITEM_SOCKET_MAX_NUM];
        for (slot, value) in sockets.iter_mut().zip(update.sockets) {
            *slot = value.unwrap_or(0);
        }
        let mut attrs = [ShopItemAttribute::default(); SHOP_ITEM_ATTRIBUTE_MAX_NUM];
        for (slot, update) in attrs.iter_mut().zip(update.attrs) {
            slot.attr_type = update.attr_type.unwrap_or(0);
            slot.value = update.value.unwrap_or(0);
        }
        Self {
            vnum: update.vnum.unwrap_or(0),
            count: update.count.unwrap_or(0),
            price: update.price.unwrap_or(0),
            price_vnum: update.price_vnum.unwrap_or(0),
            price_type: update.price_type.unwrap_or(0),
            sockets,
            attrs,
        }
    }
}

impl DecodedRenewalShopRow {
    /// Materialize this row over a fresh all-zero item slot.
    #[must_use]
    pub fn materialized_item(&self) -> RenewalShopDecodedItem {
        RenewalShopDecodedItem::from_update(&self.item)
    }
}

/// Conversion policy used by [`decode_renewal_shop_query_row_with_policy`].
